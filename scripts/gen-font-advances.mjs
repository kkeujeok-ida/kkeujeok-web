// Generates src/model/fontAdvances.generated.ts: cmap + hmtx advance widths of the two
// Pretendard OTF files (spec/text.md "Font"). Refuses files whose SHA-256 differs from
// spec/decisions/text-font.md. Run: node scripts/gen-font-advances.mjs
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const dir = fileURLToPath(new URL('../../kkeujeok-client/assets/fonts/', import.meta.url))
const FONTS = {
  regular: ['Pretendard-Regular.otf', '3ffbacde6ab8411f1d2db54bb9b1f0b3ee2a738932033722cf0388c06aed1c93'],
  bold: ['Pretendard-SemiBold.otf', 'c89bc43027dc7cde5726e96223376f8eec09302b2fc1f8147fd5b57cfc376118'],
}

function parse(buf) {
  const T = {}
  for (let i = 0, n = buf.readUInt16BE(4); i < n; i++) {
    const o = 12 + i * 16
    T[buf.toString('latin1', o, o + 4)] = buf.readUInt32BE(o + 8)
  }
  const upm = buf.readUInt16BE(T.head + 18)
  const nh = buf.readUInt16BE(T.hhea + 34)
  const advOf = (g) => buf.readUInt16BE(T.hmtx + Math.min(g, nh - 1) * 4)
  const c = T.cmap
  let off12 = -1
  for (let i = 0, n = buf.readUInt16BE(c + 2); i < n; i++) {
    if (buf.readUInt16BE(c + 4 + i * 8) === 3 && buf.readUInt16BE(c + 6 + i * 8) === 10) off12 = c + buf.readUInt32BE(c + 8 + i * 8)
  }
  if (off12 < 0) throw new Error('no format 12 cmap')
  const runs = [] // [startCp, [advances...]] for consecutive cps
  let cur = null
  for (let g = 0, n = buf.readUInt32BE(off12 + 12); g < n; g++) {
    const q = off12 + 16 + g * 12
    const s = buf.readUInt32BE(q), e = buf.readUInt32BE(q + 4), gid = buf.readUInt32BE(q + 8)
    for (let cp = s; cp <= e; cp++) {
      const a = advOf(gid + cp - s)
      if (cur && cur[0] + cur[1].length === cp) cur[1].push(a)
      else runs.push((cur = [cp, [a]]))
    }
  }
  return { upm, notdef: advOf(0), runs }
}

const out = {}
for (const [k, [file, sha]] of Object.entries(FONTS)) {
  const buf = readFileSync(dir + file)
  const h = createHash('sha256').update(buf).digest('hex')
  if (h !== sha) throw new Error(`${file}: SHA-256 ${h} differs from spec/decisions/text-font.md`)
  out[k] = parse(buf)
}
writeFileSync(
  fileURLToPath(new URL('../src/model/fontAdvances.generated.ts', import.meta.url)),
  `// Generated by scripts/gen-font-advances.mjs from the fonts of spec/decisions/text-font.md. Do not edit.\n` +
    `export type FontTable = { upm: number; notdef: number; runs: [number, number[]][] }\n` +
    `export const FONT_ADVANCES: { regular: FontTable; bold: FontTable } = ${JSON.stringify(out)}\n`,
)
